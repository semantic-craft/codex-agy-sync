import Foundation

public struct AgentSkillTemplateFile: Equatable, Sendable {
    public let relativePath: String
    public let content: String

    public init(relativePath: String, content: String) {
        self.relativePath = relativePath
        self.content = content
    }
}

public struct AgentSkillRenderContext: Equatable, Sendable {
    public let cliName: String
    public let skillName: String
    public let installBinPath: String
    public let appDisplayName: String
    public let appVersion: String

    public init(
        cliName: String = "codex-agy-sync",
        skillName: String = "codex-agy-sync",
        installBinPath: String = "~/.local/bin/codex-agy-sync",
        appDisplayName: String = "CodexAgySync",
        appVersion: String = "0.4.3"
    ) {
        self.cliName = cliName
        self.skillName = skillName
        self.installBinPath = installBinPath
        self.appDisplayName = appDisplayName
        self.appVersion = appVersion
    }
}

public enum AgentSkillTemplateRenderer: Sendable {
    public static func render(context: AgentSkillRenderContext) -> [AgentSkillTemplateFile] {
        [
            AgentSkillTemplateFile(
                relativePath: "SKILL.md",
                content: renderSkillMarkdown(context: context)
            ),
            AgentSkillTemplateFile(
                relativePath: "references/contract.md",
                content: renderContractMarkdown(context: context)
            ),
            AgentSkillTemplateFile(
                relativePath: "references/troubleshooting.md",
                content: renderTroubleshootingMarkdown(context: context)
            ),
        ]
    }

    private static func renderSkillMarkdown(context: AgentSkillRenderContext) -> String {
        let cli = context.cliName
        let bin = context.installBinPath
        return """
        ---
        name: \(context.skillName)
        description: Inspect, pair, and synchronize Codex Desktop and Antigravity sessions for a workspace via the \(cli) CLI.
        ---

        # \(context.appDisplayName) CLI Skill

        Generated by \(context.appDisplayName) v\(context.appVersion).

        ## Command Resolution

        Prefer `\(cli)` when `~/.local/bin` is on `PATH`. If a shell session does not include `~/.local/bin`, invoke the absolute fallback directly:

        ```bash
        \(bin) status --workspace .
        ```

        All mainline subcommands emit JSON on `stdout` and structured JSON errors on `stderr` with exit code `2`.

        ## Common `jq` Projection Patterns

        Keep context small by projecting only the fields you need:

        ```bash
        \(cli) status --workspace . | jq '{pairing, session_count: (.sessions | length)}'
        \(cli) pair --workspace . | jq '{workspace_path, agy_project_id, codex_project_id}'
        \(cli) inspect --workspace . --codex-thread-id <THREAD_ID> | jq '{canonical_title, completed_turns, has_inflight_turn, counts}'
        \(cli) sync --workspace . --latest --auto-pair | jq '{status, target_host, target_session_id, pairing_mode}'
        \(cli) sync --workspace . --chain | jq '{status, target_host, target_session_id}'
        \(cli) sync --workspace . --source-id <SOURCE_ID> --include-interrupted --auto-pair | jq '{status, target_session_id}'
        \(cli) sync --workspace . --reconcile --dry-run | jq '.'
        \(cli) menubar-feed --limit 6 | jq '{agy_daemon_active, codex_daemon_active, hero: .hero.title, recent_count: (.recent | length)}'
        ```

        ## Read-Only & WAL Safety Rules

        1. Never edit Codex `state_5.sqlite`, rollout JSONL files, or Antigravity `.pb` / LevelDB / SQLite stores by hand.
        2. Run `\(cli) status --workspace .` first to verify workspace pairing and live daemon reachability before mutating anything.
        3. Always preview pending receipt reconciliation with `\(cli) sync --workspace . --reconcile --dry-run` before running `\(cli) sync --workspace . --reconcile`.
        4. Never use `--include-interrupted` to cancel a live streaming turn; it only seals stopped trailing interrupted turns.

        ## Further References

        - CLI subcommands, flags, and JSON schemas: [references/contract.md](references/contract.md)
        - Diagnostics, exit codes, and recovery playbooks: [references/troubleshooting.md](references/troubleshooting.md)
        """
    }

    private static func renderContractMarkdown(context: AgentSkillRenderContext) -> String {
        let cli = context.cliName
        return """
        # \(context.appDisplayName) CLI Contract

        Version baseline: \(context.appDisplayName) v\(context.appVersion).

        ## Output & Exit Code Rules

        - `stdout`: valid JSON payload for every mainline and maintenance subcommand.
        - `stderr`: structured JSON error payload (`{"error": "<code>", "message": "<detail>"}`) on runtime failure.
        - Exit `0`: command completed cleanly.
        - Exit `2`: CLI argument error or structured domain error emitted on `stderr`.

        ## Mainline Subcommands

        | Subcommand | Purpose | Key Flags |
        | --- | --- | --- |
        | `\(cli) status` | Inspect workspace bindings, daemon liveness, sessions, and sync chains | `--workspace`, `--include-subagents` |
        | `\(cli) pair` | Register bidirectional workspace bindings on both hosts | `--workspace` |
        | `\(cli) inspect` | Decode a session ledger without mutating host state | `--workspace`, `--cascade-id`, `--codex-thread-id`, `--mode` |
        | `\(cli) sync` | Copy completed session history to a new target Desktop session or reconcile pending receipts | `--workspace`, `--direction`, `--source-id`, `--latest`, `--chain`, `--auto-pair`, `--pair-if-offline`, `--include-interrupted`, `--reconcile`, `--dry-run`, `--title` |
        | `\(cli) menubar-feed` | Emit recent workspace candidates and daemon liveness snapshot | `--workspace`, `--limit` |

        ## Maintenance Subcommands

        | Subcommand | Purpose | Key Flags |
        | --- | --- | --- |
        | `\(cli) serve` | Start or control the read-only local workbench server | `--workspace`, `--port`, `--status`, `--stop`, `--open` |
        | `\(cli) sync-session` | Offline/dual-mode reconciliation for a single session | `--workspace`, `--cascade-id`, `--codex-thread-id`, `--direction`, `--mode`, `--fork-policy`, `--include-interrupted` |
        | `\(cli) sync-workspace` | Offline/dual-mode reconciliation across all sessions in a workspace | `--workspace`, `--direction`, `--mode`, `--fork-policy`, `--include-subagents`, `--include-interrupted` |

        ## Key JSON Fields

        - `status` output:
          - `workspace`: `{ workspace_path, workspace_uri, workspace_name, agy_project_id, codex_project_id, codex_legacy_project_id }`
          - `pairing`: `{ paired, agy_registered, codex_registered, agy_project_id, codex_project_id, agy_daemon_active, codex_daemon_active, remediation_steps }`
          - `sessions`: array of `{ cascade_id, codex_thread_id, title, agy_step_count, codex_turn_count, is_subagent, nesting_depth }`
        - `sync` output:
          - `status`: receipt outcome such as `ready` or `pending`
          - `pairing_mode`: how missing workspace bindings were resolved (when auto-pairing occurred)
          - `target_host`, `target_session_id`, `source_session_id`, `workspace_path`
        - `inspect` output:
          - `workspace_path`, `canonical_title`, `total_events`, `completed_turns`, `has_inflight_turn`, `counts`, `latest_watermark`
        - `menubar-feed` output:
          - `agy_daemon_active`, `codex_daemon_active`, `hero`, `recent`, `pending_count`
        """
    }

    private static func renderTroubleshootingMarkdown(context: AgentSkillRenderContext) -> String {
        let cli = context.cliName
        let bin = context.installBinPath
        return """
        # \(context.appDisplayName) Troubleshooting Guide

        ## First Diagnostic Command

        Always start by checking workspace bindings, discovered sessions, and daemon liveness:

        ```bash
        \(cli) status --workspace .
        ```

        If `\(cli)` is not found in a non-login shell, call the installed symlink directly:

        ```bash
        \(bin) status --workspace .
        ```

        To add `~/.local/bin` to your shell `PATH`:

        ```bash
        export PATH="$HOME/.local/bin:$PATH"
        ```

        ## Structured Exit-Code-2 Errors

        | Error Code | Meaning | Recommended Fix |
        | --- | --- | --- |
        | `unpaired_workspace` | Workspace is missing a project binding on Codex or Antigravity | Re-run with `--auto-pair`, or run `\(cli) pair --workspace .` first |
        | `sync_busy_lock` | Another sync process currently holds the workspace lock | Wait for the active sync to finish, then retry `status` or `sync` |
        | `empty_session` | Selected source session has no completed turns to transfer | Complete at least one turn, or pass `--include-interrupted` for a stopped partial turn |
        | `online_rpc_unavailable` | Live desktop daemon RPC endpoint could not be reached | Ensure Codex Desktop or Antigravity is running, or inspect `pairing.remediation_steps` from `status` |
        | `file_not_found` | Specified workspace path, session ID, or custom UI file does not exist | Verify `--workspace` and session IDs with `\(cli) status --workspace .` |

        ## Pending Receipt Reconciliation

        When a previous sync left an unconfirmed pending receipt, preview reconciliation safely before applying changes:

        ```bash
        \(cli) sync --workspace . --reconcile --dry-run
        \(cli) sync --workspace . --reconcile
        ```

        Dry-run mode reports which pending receipts will be promoted or cleared without modifying state or staging directories.
        """
    }
}
